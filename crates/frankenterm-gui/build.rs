use frankenterm_build_identity::{
    AtomicComponentIdentityError, AtomicComponentRole, emit_cargo_atomic_component_marker,
    emit_cargo_source_revision,
};
use std::path::{Path, PathBuf};
use std::process::Command;

fn main() -> Result<(), AtomicComponentIdentityError> {
    println!("cargo:rerun-if-changed=build.rs");

    // Pass the target triple to the binary via cfg
    let target = std::env::var("TARGET").unwrap_or_else(|_| "unknown".to_string());
    println!("cargo:rustc-env=FRANKENTERM_TARGET_TRIPLE={target}");
    // The source commit goes into the version string the GUI announces to mux
    // clients, so `ft doctor` and `--version` can tell two builds of the same
    // semver apart (ft's own build script records the same revision).
    emit_cargo_source_revision("FRANKENTERM_GIT_HASH");
    emit_cargo_atomic_component_marker(AtomicComponentRole::FrankenTermGui)?;

    if std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows") {
        embed_windows_resources();
    }

    #[cfg(target_os = "macos")]
    {
        // Future: copy Info.plist for macOS app bundle support.
    }
    Ok(())
}

/// Resource ID of the window class icon. `LoadIconW(.., MAKEINTRESOURCEW(0x101))`
/// in frankenterm/window/src/os/windows/window.rs loads it.
const ICON_RESOURCE_ID: u32 = 0x101;

/// Links the application manifest (PerMonitorV2 DPI awareness, the UTF-8 code
/// page, common controls 6), the FrankenTerm icon and version information
/// into frankenterm-gui.exe. Without the manifest Windows treats the GUI as
/// DPI-unaware and bitmap-stretches it on any display scaled past 100%.
fn embed_windows_resources() {
    let manifest_dir = PathBuf::from(env("CARGO_MANIFEST_DIR"));
    let root = manifest_dir
        .parent()
        .and_then(Path::parent)
        .expect("crates/frankenterm-gui sits two levels below the workspace root");
    let assets = root.join("assets").join("windows");
    let manifest = assets.join("frankenterm.manifest");
    let icon = assets.join("frankenterm.ico");
    for input in [&manifest, &icon] {
        println!("cargo:rerun-if-changed={}", input.display());
    }

    let out_dir = PathBuf::from(env("OUT_DIR"));
    let script = out_dir.join("frankenterm-gui.rc");
    std::fs::write(&script, resource_script(&manifest, &icon))
        .unwrap_or_else(|err| panic!("writing {}: {err}", script.display()));

    let compiled = if std::env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc") {
        compile_with_rc(&script, &out_dir.join("frankenterm-gui.res"))
    } else {
        compile_with_windres(&script, &out_dir.join("frankenterm-gui-res.o"))
    };
    match compiled {
        // link.exe takes a compiled .res, and GNU ld a COFF object, as input.
        Ok(object) => println!("cargo:rustc-link-arg-bins={}", object.display()),
        // A cross-compiling host, such as a Linux windows-gnu check lane, may
        // have no resource compiler. A native Windows build, which is what
        // produces the shipped executable, fails instead.
        Err(reason) if !cfg!(windows) => println!(
            "cargo:warning=frankenterm-gui.exe is built without its manifest and icon: {reason}"
        ),
        Err(reason) => panic!("cannot embed the Windows resources: {reason}"),
    }
}

fn env(name: &str) -> std::ffi::OsString {
    std::env::var_os(name).unwrap_or_else(|| panic!("cargo sets {name} for build scripts"))
}

/// The resource script. It uses numeric constants instead of including
/// winres.h, so the resource compiler needs no SDK include path.
fn resource_script(manifest: &Path, icon: &Path) -> String {
    let version = env!("CARGO_PKG_VERSION");
    let mut numbers = version
        .split(|c: char| !c.is_ascii_digit())
        .filter_map(|part| part.parse::<u16>().ok());
    let mut next = || numbers.next().unwrap_or(0);
    let binary_version = format!("{},{},{},0", next(), next(), next());
    format!(
        r#"// Generated by crates/frankenterm-gui/build.rs.
// 24 is RT_MANIFEST; ID 1 is the process manifest of an executable.
1 24 "{manifest}"
{ICON_RESOURCE_ID} ICON "{icon}"
// 0x3F is VS_FFI_FILEFLAGSMASK, 0x40004 VOS_NT_WINDOWS32 and 1 VFT_APP.
1 VERSIONINFO
FILEVERSION {binary_version}
PRODUCTVERSION {binary_version}
FILEFLAGSMASK 0x3F
FILEFLAGS 0
FILEOS 0x40004
FILETYPE 1
FILESUBTYPE 0
BEGIN
    BLOCK "StringFileInfo"
    BEGIN
        BLOCK "040904B0"
        BEGIN
            VALUE "CompanyName", "Dicklesworthstone"
            VALUE "FileDescription", "FrankenTerm"
            VALUE "FileVersion", "{version}"
            VALUE "InternalName", "frankenterm-gui"
            VALUE "OriginalFilename", "frankenterm-gui.exe"
            VALUE "ProductName", "FrankenTerm"
            VALUE "ProductVersion", "{version}"
        END
    END
    BLOCK "VarFileInfo"
    BEGIN
        VALUE "Translation", 0x409, 1200
    END
END
"#,
        manifest = rc_string(manifest),
        icon = rc_string(icon),
    )
}

/// A path as the body of a resource-script string literal.
fn rc_string(path: &Path) -> String {
    path.display()
        .to_string()
        .replace('\\', "\\\\")
        .replace('"', "\"\"")
}

fn compile_with_rc(script: &Path, output: &Path) -> Result<PathBuf, String> {
    let rc = find_rc().ok_or_else(|| {
        "rc.exe was not found in RC, PATH or the Windows 10/11 SDK; \
         run the build from a Visual Studio developer environment (vcvars64.bat)"
            .to_owned()
    })?;
    run(Command::new(&rc)
        .arg("/nologo")
        .arg("/fo")
        .arg(output)
        .arg(script))?;
    Ok(output.to_owned())
}

/// The SDK's rc.exe: `RC`, then PATH (a developer environment puts the SDK
/// there), then the newest installed Windows 10/11 SDK.
fn find_rc() -> Option<PathBuf> {
    println!("cargo:rerun-if-env-changed=RC");
    if let Some(rc) = std::env::var_os("RC") {
        return Some(rc.into());
    }
    if let Some(found) = std::env::var_os("PATH").and_then(|path| {
        std::env::split_paths(&path)
            .map(|dir| dir.join("rc.exe"))
            .find(|rc| rc.is_file())
    }) {
        return Some(found);
    }
    // rc.exe runs on the build host, so take the host architecture's copy.
    let host_arch = if cfg!(target_arch = "aarch64") {
        "arm64"
    } else if cfg!(target_arch = "x86") {
        "x86"
    } else {
        "x64"
    };
    let kits = std::env::var_os("ProgramFiles(x86)")
        .map(PathBuf::from)?
        .join("Windows Kits")
        .join("10")
        .join("bin");
    let mut versions: Vec<(Vec<u32>, PathBuf)> = std::fs::read_dir(&kits)
        .ok()?
        .filter_map(Result::ok)
        .filter_map(|entry| {
            let name = entry.file_name().into_string().ok()?;
            let version = name
                .split('.')
                .map(str::parse)
                .collect::<Result<Vec<u32>, _>>()
                .ok()?;
            Some((version, entry.path().join(host_arch).join("rc.exe")))
        })
        .filter(|(_, rc)| rc.is_file())
        .collect();
    versions.sort();
    versions.pop().map(|(_, rc)| rc)
}

fn compile_with_windres(script: &Path, output: &Path) -> Result<PathBuf, String> {
    println!("cargo:rerun-if-env-changed=WINDRES");
    let target = std::env::var("TARGET").unwrap_or_default();
    let candidates = std::env::var("WINDRES").ok().into_iter().chain([
        // The MinGW cross toolchain prefixes its tools with the GNU triple.
        target.replace("-pc-windows-gnu", "-w64-mingw32-windres"),
        "windres".to_owned(),
    ]);
    let mut failures = vec![];
    for windres in candidates {
        let mut command = Command::new(&windres);
        command
            .arg("--input")
            .arg(script)
            .arg("--output")
            .arg(output)
            .arg("--output-format=coff");
        match run(&mut command) {
            Ok(()) => return Ok(output.to_owned()),
            Err(reason) => failures.push(reason),
        }
    }
    Err(failures.join("; "))
}

fn run(command: &mut Command) -> Result<(), String> {
    let output = command
        .output()
        .map_err(|err| format!("{command:?}: {err}"))?;
    if output.status.success() {
        Ok(())
    } else {
        Err(format!(
            "{command:?} exited with {}: {}{}",
            output.status,
            String::from_utf8_lossy(&output.stdout).trim(),
            String::from_utf8_lossy(&output.stderr).trim()
        ))
    }
}
